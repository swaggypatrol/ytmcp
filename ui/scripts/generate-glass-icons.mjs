// Regenerates ui/src/lib/icons/glass-icons.generated.ts from an extracted Glass Music Icons pack.
//
//   node ui/scripts/generate-glass-icons.mjs <path-to-glass-music-icons>
//
// Reads only svg/outline/<name>.svg and svg/filled/<name>.svg for the names listed below. Each
// file is parsed into plain element descriptors; anything outside the element and attribute
// allowlists aborts the run, so no markup from the pack reaches the app unchecked.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = [
  "home", "search", "library", "heart", "recent", "album", "queue-list", "lyrics", "settings",
  "previous", "next", "play", "pause", "chevron-left", "chevron-right", "chevron-up",
  "chevron-down", "more", "close", "volume-high", "volume-medium", "volume-low", "volume-mute",
  "shuffle", "repeat", "repeat-one", "plus", "artist", "check", "add-to-queue", "play-next",
  "radio",
];
const ELEMENTS = new Set(["path", "circle", "rect", "line", "polyline", "polygon", "g"]);
const ATTRIBUTES = new Set([
  "d", "cx", "cy", "r", "x", "y", "width", "height", "rx", "ry", "x1", "y1", "x2", "y2", "points",
  "fill", "stroke", "stroke-width",
]);
const ROOT = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1\.75" stroke-linecap="round" stroke-linejoin="round">(.*)<\/svg>\s*$/s;

function parse(file) {
  const match = ROOT.exec(readFileSync(file, "utf8"));
  if (!match) throw new Error(`${file}: unexpected root element`);
  const elements = [];
  const body = match[1];
  const pattern = /<([a-z]+)((?:\s+[a-z-]+="[^"<>]*")*)\s*\/>/gy;
  let consumed = 0;
  for (const [whole, tag, attrText] of body.matchAll(pattern)) {
    consumed += whole.length;
    if (!ELEMENTS.has(tag)) throw new Error(`${file}: element <${tag}> is not allowed`);
    const attrs = {};
    for (const [, key, value] of attrText.matchAll(/([a-z-]+)="([^"]*)"/g)) {
      if (!ATTRIBUTES.has(key)) throw new Error(`${file}: attribute ${key} is not allowed`);
      if ((key === "fill" || key === "stroke") && value !== "currentColor" && value !== "none") {
        throw new Error(`${file}: ${key}="${value}" is not currentColor/none`);
      }
      attrs[key] = value;
    }
    elements.push([tag, attrs]);
  }
  if (consumed !== body.length) throw new Error(`${file}: content outside self-closing elements`);
  return elements;
}

const pack = process.argv[2];
if (!pack) throw new Error("usage: generate-glass-icons.mjs <pack-dir>");
const outline = {};
const filled = {};
for (const name of NAMES) {
  outline[name] = parse(join(pack, "svg/outline", `${name}.svg`));
  const filledFile = join(pack, "svg/filled", `${name}.svg`);
  if (existsSync(filledFile)) filled[name] = parse(filledFile);
}

const out = join(dirname(fileURLToPath(import.meta.url)), "../src/lib/icons/glass-icons.generated.ts");
writeFileSync(
  out,
  `// Generated by ui/scripts/generate-glass-icons.mjs from Glass Music Icons 1.0.0. Do not edit.\n` +
    `import type { GlassGlyph } from "./glyph.js";\n\n` +
    `export const OUTLINE = ${JSON.stringify(outline, null, 2)} as const satisfies Record<string, GlassGlyph>;\n\n` +
    `export const FILLED = ${JSON.stringify(filled, null, 2)} as const satisfies Record<string, GlassGlyph>;\n`
);
console.log(`wrote ${Object.keys(outline).length} outline and ${Object.keys(filled).length} filled glyphs`);
